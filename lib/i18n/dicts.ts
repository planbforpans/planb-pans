// The translation store for the server-rendered pages. data/translations/<lang>.json
// is generated by `npm run translations` (scripts/translations/build.mjs) through
// the same translation service the in-page picker uses; hand corrections go in
// data/translations/overrides/<lang>.json and always win. Nothing is translated
// while a page is being served: the store is read at build time.

const GENERATED: Record<Locale, Dict> = { es, fr, de, pt, it, 'zh-Hans': zhHans, 'zh-Hant': zhHant, ja, ar }
const OVERRIDES: Record<Locale, Dict> = { es: esO, fr: frO, de: deO, pt: ptO, it: itO, 'zh-Hans': zhHansO, 'zh-Hant': zhHantO, ja: jaO, ar: arO }
const PAGES = pages as Record<string, string[]>

const merged = new Map<Locale, { dict: Dict; reverse: Map<string, string> }>()

function load(locale: Locale) {
  let m = merged.get(locale)
  if (!m) {
    const dict: Dict = { ...GENERATED[locale], ...OVERRIDES[locale] }
    const reverse = new Map<string, string>()
    for (const [en, tr] of Object.entries(dict)) if (tr && tr !== en) reverse.set(tr, en)
    m = { dict, reverse }
    merged.set(locale, m)
  }
  return m
}

export function dictFor(locale: Locale): Dict {
  return load(locale).dict
}

// Turn on translation for the rest of this server render (see lib/i18n/adapt.ts).
export function enableServerLocale(locale: Locale) {
  const st = serverI18n()
  const m = load(locale)
  st.locale = locale
  st.dict = m.dict
  st.reverse = m.reverse
}

export function tr(locale: Locale, s: string): string {
  return lookup(dictFor(locale), s)
}

// The phrases one page shows, for the client components on it (<T>) and the
// in-page picker. Keeps the page's payload to what it needs.
export function pageDict(locale: Locale, path: string): Dict {
  const dict = dictFor(locale)
  const keys = PAGES[path] || []
  const out: Dict = {}
  // Phrases that stay as they are (names, codes) are included so the picker never sends them off.
  for (const k of keys) if (dict[k]) out[k] = dict[k]
  return out
}

const OG_IMAGE: Record<string, string> = {
  '/for-autism': '/for-autism/opengraph-image',
  '/for-ocd': '/for-ocd/opengraph-image',
  '/for-arfid': '/for-arfid/opengraph-image',
  '/for-adhd': '/for-adhd/opengraph-image',
  '/for-constipation': '/for-constipation/opengraph-image',
  '/learning/behaviors-are-a-clue': '/learning/behaviors-are-a-clue/opengraph-image',
}

function trTitle(locale: Locale, t: Metadata['title']): Metadata['title'] {
  if (typeof t === 'string') return tr(locale, t)
  if (t && typeof t === 'object' && 'absolute' in t && typeof t.absolute === 'string') return tr(locale, t.absolute)
  if (t && typeof t === 'object' && 'default' in t && typeof t.default === 'string') return tr(locale, t.default)
  return t
}

// The English page's <title>, description and social text in the page's language,
// with its own canonical URL and hreflang links to every other language.
export function localizedMetadata(locale: Locale, path: string, en: Metadata): Metadata {
  const url = `https://planbforpans.com${localePath(locale, path)}`
  const title = trTitle(locale, en.title)
  const description = typeof en.description === 'string' ? tr(locale, en.description) : en.description
  const og = (en.openGraph || {}) as Record<string, unknown>
  const tw = (en.twitter || {}) as Record<string, unknown>
  const image = OG_IMAGE[path]
  return {
    ...en,
    title: typeof title === 'string' ? { absolute: title } : title,
    description,
    alternates: { canonical: url, languages: languageAlternates(path) },
    openGraph: {
      ...og,
      title: typeof og.title === 'string' ? tr(locale, og.title) : (typeof title === 'string' ? title : undefined),
      description: typeof og.description === 'string' ? tr(locale, og.description) : description ?? undefined,
      url,
      locale: OG_LOCALE[locale],
      alternateLocale: ['en_US', ...LOCALES.filter((l) => l !== locale).map((l) => OG_LOCALE[l])],
      ...(image ? { images: [`https://planbforpans.com${image}`] } : {}),
    },
    twitter: {
      ...tw,
      title: typeof tw.title === 'string' ? tr(locale, tw.title) : (typeof title === 'string' ? title : undefined),
      description: typeof tw.description === 'string' ? tr(locale, tw.description) : description ?? undefined,
      ...(image ? { images: [`https://planbforpans.com${image}`] } : {}),
    },
  } as Metadata
}
